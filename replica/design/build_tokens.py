#!/usr/bin/env python3
"""Generate CSS from replica/design/tokens.json. Standard library only.

    python3 replica/design/build_tokens.py

Writes two files, next to this script and, when the app exists, into
src/styles/:

  tokens.css          plain CSS custom properties. Light on :root, dark on
                      [data-theme="dark"] and for "system" users whose OS is dark.
  tailwind-theme.css  Tailwind v4 @theme block mapping the roles to utilities
                      (bg-surface, text-text-muted, border-border-input, ...).
                      It clears Tailwind's default palette and type scale, so
                      raw colours like bg-blue-500 don't exist in the app.

tokens.json is the source of truth. Edit it, re-run this, then the contrast check.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
HEADER = "/* Generated by replica/design/build_tokens.py from tokens.json. Do not edit. */\n"


def px(n):
    return "0" if n == 0 else "%dpx" % n


def colour_vars(colours, indent="  "):
    return "\n".join("%s--c-%s: %s;" % (indent, k, v) for k, v in colours.items())


def build(tokens):
    col = dict(tokens["color"])
    dark = col.pop("dark")
    light = {k: v for k, v in col.items() if isinstance(v, str)}
    missing = sorted(set(light) ^ set(dark))
    if missing:
        sys.exit("build_tokens: light and dark roles differ: %s" % ", ".join(missing))

    t = tokens["type"]
    lay = tokens["layout"]

    base = []
    base.append(":root {")
    base.append("  color-scheme: light;")
    base.append(colour_vars(light))
    base.append("  --font-ui: %s;" % tokens["font"]["sans"])
    base.append("  --font-code: %s;" % tokens["font"]["mono"])
    for k, v in tokens["radius"].items():
        base.append("  --r-%s: %s;" % (k, px(v)))
    for k, v in tokens["shadow"].items():
        base.append("  --sh-%s: %s;" % (k, v))
    for k, v in tokens["motion"].items():
        base.append("  --motion-%s: %s;" % (k, v))
    for k, v in tokens["size"].items():
        base.append("  --size-%s: %s;" % (k, px(v)))
    for k, v in lay.items():
        if isinstance(v, (int, float)):
            base.append("  --layout-%s: %s;" % (k, px(v)))
    for k, v in tokens["z"].items():
        base.append("  --z-%s: %s;" % (k, v))
    base.append("}")
    base.append("")
    base.append(':root[data-theme="dark"] {')
    base.append("  color-scheme: dark;")
    base.append(colour_vars(dark))
    base.append("}")
    base.append("")
    base.append("@media (prefers-color-scheme: dark) {")
    base.append('  :root:not([data-theme="light"]) {')
    base.append("    color-scheme: dark;")
    base.append(colour_vars(dark, "    "))
    base.append("  }")
    base.append("}")
    base.append("")
    base.append("@media (prefers-reduced-motion: reduce) {")
    base.append("  :root { --motion-fast: 0ms; --motion-base: 0ms; --motion-slow: 0ms; }")
    base.append("}")
    tokens_css = HEADER + "\n".join(base) + "\n"

    th = []
    th.append("@theme inline {")
    th.append("  --color-*: initial;")
    th.append("  --color-transparent: transparent;")
    th.append("  --color-current: currentColor;")
    for k in light:
        th.append("  --color-%s: var(--c-%s);" % (k, k))
    th.append("")
    th.append("  --font-*: initial;")
    th.append("  --font-sans: var(--font-ui);")
    th.append("  --font-mono: var(--font-code);")
    th.append("")
    th.append("  --text-*: initial;")
    for k, v in t.items():
        th.append("  --text-%s: %s;" % (k, px(v["size"])))
        th.append("  --text-%s--line-height: %s;" % (k, px(v["line"])))
        th.append("  --text-%s--font-weight: %s;" % (k, v["weight"]))
    th.append("")
    th.append("  --radius-*: initial;")
    for k in tokens["radius"]:
        th.append("  --radius-%s: var(--r-%s);" % (k, k))
    th.append("")
    th.append("  --shadow-*: initial;")
    for k in tokens["shadow"]:
        th.append("  --shadow-%s: var(--sh-%s);" % (k, k))
    th.append("")
    th.append("  --spacing: 4px;")
    for k, v in lay["breakpoints"].items():
        th.append("  --breakpoint-%s: %s;" % (k, px(v)))
    th.append("")
    th.append("  --ease-standard: %s;" % tokens["motion"]["ease"])
    th.append("}")
    theme_css = HEADER + "\n".join(th) + "\n"
    return tokens_css, theme_css


def main():
    with open(os.path.join(HERE, "tokens.json"), encoding="utf-8") as fh:
        tokens = json.load(fh)
    tokens_css, theme_css = build(tokens)
    targets = [HERE]
    app_styles = os.path.join(ROOT, "src", "styles")
    if os.path.isdir(app_styles):
        targets.append(app_styles)
    for d in targets:
        for name, body in (("tokens.css", tokens_css), ("tailwind-theme.css", theme_css)):
            path = os.path.join(d, name)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(body)
            print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
